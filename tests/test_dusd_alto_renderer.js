const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const ctx=vm.createContext({console,window:{},document:{getElementById:()=>null,querySelectorAll:()=>[]}});
vm.runInContext(fs.readFileSync('js/renderers/common.js','utf8')+'\nthis.CommonRenderer=CommonRenderer;',ctx);
vm.runInContext(fs.readFileSync('js/renderers/dusd-alto.js','utf8'),ctx);
vm.runInContext(fs.readFileSync('js/issuer-project-evidence.js','utf8'),ctx);
const renderer=ctx.DusdAltoRenderer;
const d=JSON.parse(fs.readFileSync('data/dusd_alto_backing.json','utf8'));
const b=d.backing;
assert.equal(b.cdp.ratio,null);
const coverage=renderer._trancheCoverageHtml(b);
assert.match(coverage,/Not established/);
assert.match(coverage,/12\.4% of issued DUSD/);
assert.doesNotMatch(coverage,/88%|8\.6%|WORST SUSTAINABLE|insolvency/);
assert.match(coverage,/not establish a loss/);
assert.match(renderer._usmHtml(b,d.asset_specific,d),/12\.4% of issued DUSD/);
assert.doesNotMatch(renderer._usmHtml(b,d.asset_specific,d),/16-lifetime|sole-SWAPPER/);
const lp=renderer._creditLineHtml(b);
assert.match(lp,/Own DUSD is circular and excluded from external backing/);
assert.match(lp,/pro-rata pool-balance allocations, not executable proceeds/);
assert.match(lp,/Fixed-oracle nominal LP mark/);
const markets=renderer._cdpHtml(b);
assert.match(markets,/Nominal oracle mark \(DUSD\)/);
assert.doesNotMatch(markets,/~12%|Collateral \(USD\)/);
const feed=JSON.parse(fs.readFileSync('data/issuer_project_evidence.json','utf8'));
const evidence=ctx.IssuerProjectEvidence;
const html=evidence.html(feed,'dusd-alto');
assert.match(html,/Alto Foundation/);
assert.match(html,/Mesh Interface Corp/);
assert.match(html,/Product issuer\/repayment obligor not established/);
assert.match(html,/data-issuer-summary="true"/);
assert.match(html,/Selected legal, custody and assurance sources/);
assert.match(html,/source 1: effective 2026-10-22, retrieved/);
assert.doesNotMatch(html,/\[object Object\]|raw_sha256|profile_sha256|undefined|no legal entity|without incident since/);
assert.equal(evidence.observationDatesText(['2026-01-01','2026-02-01']),'2026-01-01 · 2026-02-01');
const unknown=JSON.parse(JSON.stringify(feed));unknown.component_profiles['dusd-alto'].status='unavailable_selected_source';
assert.match(evidence.html(unknown,'dusd-alto'),/no project, family or underlying rights are substituted/);
console.log('PASS Alto scope, dynamic issuance, unknown valuation, staked LP separation and component-source/date rendering');

const liquidity=JSON.parse(fs.readFileSync('data/dusd_alto_liquidity.json','utf8'));
const exit=renderer._exitRealityHtml({liquidity});
assert.match(exit,/Indicative USDC output/);
assert.match(exit,/Above-supply mathematical observations/);
assert.match(exit,/Current economic public float.*not established/);
assert.doesNotMatch(exit,/Supply outside pool:.*1,000,000|float is the cap|SCARCE coin/);
ctx.CommonRenderer._adaptSchema('liquidity','liquidity/1',liquidity);
assert.ok(!liquidity.exit_mark || !liquidity.exit_mark.quotes);
const depth=ctx.CommonRenderer.depthAtLimit({asset_slug:'dusd-alto',liquidity});
assert.equal(depth.shape,'quote_sample');
assert.equal(depth.value,1000000);
assert.equal(ctx.CommonRenderer._depthLabel({asset_slug:'dusd-alto',liquidity}),'quoted sample');
assert.ok(ctx.CommonRenderer.DEPTH_NON_DERIVABLE_STATUSES.includes(liquidity.two_pct_depth_status));
console.log('PASS quote-only sample cannot become executable depth or public float');
const contract=JSON.parse(fs.readFileSync('data/dusd_alto_contract.json','utf8'));
assert.equal(contract.as_of,'2026-11-07T02:39:35Z');
assert.match(contract.contract.headline,/24h/);
assert.match(contract.contract.headline,/one of seven owner keys/);
assert.ok(contract.contract.layers.every(l=>l.reach==='partial'));
const authored=JSON.parse(fs.readFileSync('data/dusd_alto_backing_overlay.json','utf8'));
assert.equal(authored.backing.backing_score,5);
assert.equal(authored.backing.assessment_version,'dusd-alto-2026-11-07-v2');
console.log('PASS bounded current authority and adopted authored backing score');
