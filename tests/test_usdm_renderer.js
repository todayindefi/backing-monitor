const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ctx = vm.createContext({document: {getElementById: () => null}, console});
vm.runInContext(fs.readFileSync('js/renderers/common.js', 'utf8') + '\nthis.common=CommonRenderer;', ctx);
vm.runInContext(fs.readFileSync('js/renderers/usdm.js', 'utf8'), ctx);
const c=ctx.common, r=ctx.USDmRenderer;
const data=JSON.parse(fs.readFileSync('data/usdm_backing.json','utf8'));
const agg=data.asset_specific.aggregate;
r.preRender(data,{entries:[]});
assert.ok(Math.abs(data.backing_breakdown.reduce((s,x)=>s+x.value,0)-agg.total_reserve_usd)<0.1);
assert.ok(Math.abs(data.backing_breakdown.reduce((s,x)=>s+x.pct,0)-100)<0.001);
const html=r._renderHeadlineCard(data.asset_specific,data.summary);
assert.match(html,/LP collateral/);
assert.doesNotMatch(html,/AUSD.*absent from the API|all 7 reserve wallets|user-relevant/);
const value=c._depthValueHtml({liquidity:{two_pct_depth_status:'not_size_responsive',exit_capacity:{capacity_usd:24436}}});
assert.match(value,/24/);
assert.match(value,/inventory bound/);
assert.equal(c._depthValueHtml({liquidity:{exit_capacity:{capacity_usd:24436}}}),'n/a');
console.log('USDM scope, allocation and inventory fallback checks passed');
